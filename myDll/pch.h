/**
 * @file pch.h
 * @brief 预编译头文件（Precompiled Header）
 * @details 预编译头技术可以显著提高大型项目的编译速度
 * 
 * 工作原理：
 * - 编译器首次编译时会处理此文件中包含的所有头文件，并将结果保存为.pch文件
 * - 后续编译时直接使用预编译结果，无需重新解析这些头文件
 * - 可以将编译时间从几分钟减少到几秒钟
 * 
 * 使用建议：
 * - 将稳定的、不常修改的头文件（如标准库、第三方库）放在此处
 * - 不要将频繁修改的项目头文件放在此处，否则会失去性能优势
 * - 所有.cpp文件的第一行应该是 #include "pch.h"
 * 
 * 影响范围：
 * - IntelliSense代码补全和语法高亮
 * - 编译速度（可提升50%以上）
 * - 增量编译效率
 */

